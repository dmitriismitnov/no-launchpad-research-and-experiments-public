/**
 * Icon manifest: the stable contract between the source SVGs and the runtime
 * component.
 *
 * A key is the source SVG file name; a value is its private-use codepoint.
 * Existing keys always keep their codepoint. New keys continue after the
 * highest codepoint currently assigned; because a removed key leaves the
 * manifest entirely, its codepoint can later be reused by a different key.
 * That is safe here because the font and the manifest are always rebuilt
 * together from the same source set, and the bundler hashes the font asset.
 */

export type IconCodepoints = Readonly<Record<string, number>>;

/** First codepoint of the Unicode Private Use Area block used for icons. */
export const FIRST_CODEPOINT = 0xE001;

/** Last codepoint of the Unicode Private Use Area block used for icons. */
const LAST_CODEPOINT = 0xF8FF;

export const MANIFEST_HEADER = "// Generated by src/shared/components/icon/tools/build.ts. Do not edit by hand.";

type CodepointRange = {
    first?: number;
    last?: number;
};

const toHex = (codepoint: number): string => `0x${codepoint.toString(16).toUpperCase()}`;

/**
 * Assigns codepoints to `names` while preserving every codepoint already in
 * `current`. New names are processed in sorted order and continue after the
 * highest used codepoint.
 */
export const assignCodepoints = (
    current: IconCodepoints,
    names: readonly string[],
    range: CodepointRange = {},
): { codepoints: IconCodepoints; added: string[]; } => {
    const first = range.first ?? FIRST_CODEPOINT;
    const last = range.last ?? LAST_CODEPOINT;
    const unique = new Set(names);

    if ( unique.size !== names.length ) {
        throw new Error("icon names must be unique");
    }

    const codepoints: Record<string, number> = {};
    let highest = first - 1;

    for ( const name of [ ...names, ].sort() ) {
        const existing = current[name];

        if ( existing !== undefined ) {
            codepoints[name] = existing;
            highest = Math.max(highest, existing);
        }
    }

    const added: string[] = [];

    for ( const name of [ ...names, ].sort() ) {
        if ( codepoints[name] !== undefined ) {
            continue;
        }

        const next = highest + 1;

        if ( next > last ) {
            throw new Error(`ran out of codepoints in the private use area at "${name}"`);
        }

        codepoints[name] = next;
        highest = next;
        added.push(name);
    }

    return { codepoints, added, };
};

/**
 * Renders the generated TypeScript manifest. Attributes are sorted by name so
 * the output is byte-stable for the same mapping.
 */
export const renderManifest = (codepoints: IconCodepoints): string => {
    const entries = Object.entries(codepoints)
        .sort(([ a, ], [ b, ]) => ( a < b ? -1 : a > b ? 1 : 0 ))
        .map(([ name, codepoint, ]) => `    "${name}": ${toHex(codepoint)},`)
        .join("\n");

    return `${MANIFEST_HEADER}

/** Public icon keys. Each key is the name of a source SVG file. */
export const ICON_CODEPOINTS = {
${entries}
} as const;

export type IconName = keyof typeof ICON_CODEPOINTS;
`;
};

/**
 * Reads the codepoint mapping back out of a generated manifest.
 */
export const parseManifest = (source: string): IconCodepoints => {
    const codepoints: Record<string, number> = {};
    const pattern = /^\s*"([^"]+)"\s*:\s*0x([0-9A-Fa-f]+)\s*,?\s*$/gm;
    let match: RegExpExecArray | null;

    while ( ( match = pattern.exec(source) ) !== null ) {
        const name = match[1] ?? "";
        const value = match[2] ?? "";
        codepoints[name] = Number.parseInt(value, 16);
    }

    return codepoints;
};
