/**
 * Web-font manifest: the stable contract between the canonical font sources and
 * the runtime `@font-face` registration.
 *
 * The manifest is rendered only from validated face data, in the canonical
 * `fontFaces` order. It never contains host paths, timestamps or build-time
 * hashes, so rebuilding unchanged sources produces an identical file.
 */

import { basename, } from "node:path";

import { FONT_FAMILY, } from "../constants";
import type { ValidatedFontFace, } from "./font";

const MANIFEST_HEADER = "// Generated by src/shared/fonts/tools/build.ts. Do not edit by hand.";
const literalUnion = (values: readonly string[]): string =>
    [ ...new Set(values), ].map((value) => `"${value}"`).join(" | ");

const renderFace = (face: ValidatedFontFace): string =>
    `    {
        id: "${face.id}",
        family: "${face.family}",
        style: "${face.style}",
        weightRange: "${face.weightRange}",
        axes: [ ${face.axes.map((axis) => `"${axis}"`).join(", ")} ],
        fileName: "${basename(face.outputPath)}",
    },`;

/** Renders the committed TypeScript manifest for the given validated faces. */
export const renderManifest = (faces: readonly ValidatedFontFace[]): string => {
    const first = faces[0];

    if ( first === undefined ) {
        throw new Error("cannot render a font manifest without faces");
    }

    const ids = faces.map((face) => face.id);
    const styles = faces.map((face) => face.style);
    const weightRanges = faces.map((face) => face.weightRange);
    const axes = first.axes.map((axis) => `"${axis}"`).join(", ");
    const bodies = faces.map(renderFace).join("\n");

    return `${MANIFEST_HEADER}
// Run \`mise run fonts:build\` to regenerate.

export type WebFontFace = {
    id: ${literalUnion(ids)};
    family: "${FONT_FAMILY}";
    style: ${literalUnion(styles)};
    weightRange: ${literalUnion(weightRanges)};
    axes: readonly [ ${axes} ];
    /** File name inside the generated web-font directory. */
    fileName: string;
};

export const WEB_FONT_FACES: readonly WebFontFace[] = [
${bodies}
];
`;
};
