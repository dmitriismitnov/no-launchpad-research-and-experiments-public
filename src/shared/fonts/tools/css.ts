/**
 * Runtime `@font-face` CSS renderer.
 *
 * The CSS is rendered only from validated face data, in the canonical
 * `fontFaces` order. URLs stay relative to the generated stylesheet so the
 * output never contains host paths and rebuilding unchanged sources produces
 * an identical file.
 */

import { dirname, relative, sep, } from "node:path";

import type { ValidatedFontFace, } from "./font";

export const CSS_HEADER = "/* Generated by src/shared/fonts/tools/build.ts. Do not edit by hand. */";

const toCssUrl = (outputPath: string, cssPath: string): string => {
    const path = relative(dirname(cssPath), outputPath).split(sep).join("/");

    return path.startsWith(".") ? path : `./${path}`;
};

/** Renders the committed runtime stylesheet for the given validated faces. */
export const renderFontCss = (faces: readonly ValidatedFontFace[], cssPath: string): string => {
    if ( faces.length === 0 ) {
        throw new Error("cannot render font CSS without faces");
    }

    const blocks = faces.map((face) =>
        `@font-face {
    font-family: "${face.family}";
    font-style: ${face.style};
    font-weight: ${face.weightRange};
    font-display: swap;
    src: url("${toCssUrl(face.outputPath, cssPath)}") format("woff2");
}`
    );

    return `${CSS_HEADER}
/* Run \`mise run fonts:build\` to regenerate. */

${blocks.join("\n\n")}
`;
};
